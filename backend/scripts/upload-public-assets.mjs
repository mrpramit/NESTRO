import "dotenv/config";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { v2 as cloudinary } from "cloudinary";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const workspaceDirectory = path.resolve(scriptDirectory, "../..");
const publicDirectory = path.join(workspaceDirectory, "fronted", "public");
const manifestPath = path.join(
	workspaceDirectory,
	"fronted",
	"src",
	"utils",
	"cloudinaryAssets.js",
);
const supportedExtensions = new Set([
	".png",
	".jpg",
	".jpeg",
	".webp",
	".gif",
	".svg",
]);

cloudinary.config({
	cloud_name: process.env.CLOUD_NAME,
	api_key: process.env.API_KEY,
	api_secret: process.env.API_SECRET,
	secure: true,
});

const files = (await fs.readdir(publicDirectory, { withFileTypes: true }))
	.filter((entry) => entry.isFile())
	.map((entry) => entry.name)
	.filter((fileName) => supportedExtensions.has(path.extname(fileName).toLowerCase()))
	.sort();

if (files.length === 0) {
	throw new Error(`No supported assets found in ${publicDirectory}`);
}

const assets = {};
for (const fileName of files) {
	const filePath = path.join(publicDirectory, fileName);
	const publicId = path.basename(fileName, path.extname(fileName));
	const result = await cloudinary.uploader.upload(filePath, {
		folder: "nestro/static",
		public_id: publicId,
		resource_type: "image",
		use_filename: false,
		unique_filename: false,
		overwrite: true,
		invalidate: true,
	});

	assets[fileName] = result.secure_url;
	console.log(`Uploaded ${fileName}`);
}

const manifest = `// Generated by backend/scripts/upload-public-assets.mjs\nexport const cloudinaryAssets = ${JSON.stringify(assets, null, 2)};\n`;
await fs.writeFile(manifestPath, manifest, "utf8");
console.log(`Wrote ${path.relative(workspaceDirectory, manifestPath)}`);